def create_workbook():
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)

    workbook = Workbook()
    worksheet = workbook.active
    worksheet.title = "Data Dictionary"

    columns = [
        "Variable Name",
        "Label / Description",
        "Data Type",
        "Measurement Level",
        "Unit",
        "Valid Values / Codes",
        "Missing Value Treatment",
        "Questionnaire Section",
        "Indicator Linkage",
        "Derived Variable",
        "Calculation / Derivation Rule",
    ]

    worksheet.append(columns)

    for variable in VARIABLES:
        worksheet.append([
            variable["variable_name"],
            variable["label"],
            variable["data_type"],
            variable["measurement_level"],
            variable["unit"],
            variable["valid_values"],
            variable["missing_treatment"],
            variable["questionnaire_section"],
            variable["indicator_linkage"],
            variable["derived"],
            variable["calculation_rule"],
        ])

    # Metadata sheet
    metadata = workbook.create_sheet("Dictionary Metadata")
    metadata_rows = [
        ("Project", "Agricultural Livelihoods and MSME Development Project (ALMDP)"),
        ("Location", "Kaduna State, Nigeria"),
        ("Dataset", "Synthetic baseline dataset"),
        ("Purpose", "Define variables, coding, measurement, derivation, and indicator linkage"),
        ("Status", "Synthetic / Simulated Portfolio Project"),
        ("Source", "ALMDP Baseline Questionnaire and M&E Framework"),
    ]

    for row in metadata_rows:
        metadata.append(row)

    # Variable summary
    summary = workbook.create_sheet("Variable Summary")
    summary.append(["Metric", "Value"])
    summary.append(["Total variables", len(VARIABLES)])
    summary.append([
        "Derived variables",
        sum(1 for v in VARIABLES if v["derived"] == "Yes"),
    ])
    summary.append([
        "Source variables",
        sum(1 for v in VARIABLES if v["derived"] == "No"),
    ])

    # Formatting
    header_fill = PatternFill(
        fill_type="solid",
        fgColor="1F4E78",
    )

    for sheet in workbook.worksheets:
        sheet.freeze_panes = "A2"

        for cell in sheet[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = header_fill
            cell.alignment = Alignment(
                horizontal="center",
                vertical="center",
                wrap_text=True,
            )

        for row in sheet.iter_rows():
            for cell in row:
                cell.alignment = Alignment(
                    vertical="top",
                    wrap_text=True,
                )

    widths = [
        28, 42, 18, 20, 18, 55, 55,
        20, 35, 18, 65,
    ]

    for index, width in enumerate(widths, start=1):
        worksheet.column_dimensions[get_column_letter(index)].width = width

    metadata.column_dimensions["A"].width = 24
    metadata.column_dimensions["B"].width = 80

    summary.column_dimensions["A"].width = 28
    summary.column_dimensions["B"].width = 20

    worksheet.auto_filter.ref = worksheet.dimensions

    workbook.save(OUTPUT_FILE)

    print(f"Created: {OUTPUT_FILE}")
    print(f"Variables: {len(VARIABLES)}")


if __name__ == "__main__":
    create_workbook()